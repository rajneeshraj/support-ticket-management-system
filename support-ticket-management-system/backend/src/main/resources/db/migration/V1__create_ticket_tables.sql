CREATE TABLE ticket (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150)  NOT NULL,
    description VARCHAR(5000) NOT NULL,
    status      VARCHAR(20)   NOT NULL DEFAULT 'OPEN',
    priority    VARCHAR(20)   NOT NULL DEFAULT 'MEDIUM',
    assignee    VARCHAR(100),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    version     BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_ticket_status
        CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED')),
    CONSTRAINT ck_ticket_priority
        CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL'))
);

CREATE INDEX idx_ticket_status_created ON ticket (status, created_at DESC);
CREATE INDEX idx_ticket_created ON ticket (created_at DESC);

CREATE TABLE comment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT        NOT NULL,
    author     VARCHAR(100)  NOT NULL,
    text       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_comment_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id)
);

CREATE INDEX idx_comment_ticket_created ON comment (ticket_id, created_at);
